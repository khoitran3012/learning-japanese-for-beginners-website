const BY_CHAR = new Map<string, KanjiLesson>();
for (const lesson of KANJI_LESSONS) {
  for (const ch of lesson.chars) {
    if (!BY_CHAR.has(ch)) BY_CHAR.set(ch, lesson);
  }
}

export function kanjiLessonOf(character: string) {
  return BY_CHAR.get(character);
}

export function kanjiLessonsFor(level: "all" | JlptLevel) {
  if (level === "all") return KANJI_LESSONS;
  return KANJI_LESSONS.filter((l) => l.level === level);
}

export function kanjiLessonById(id: string) {
  return KANJI_LESSONS.find((l) => l.id === id);
}

export function kanjiLessonByPath(pathId: string) {
  return KANJI_LESSONS.find((l) => l.pathLessonId === pathId);
}

export function kanjiLessonsByPath(pathId: string) {
  return KANJI_LESSONS.filter((l) => l.pathLessonId === pathId);
}

/** Chỉ số chữ trong thứ tự học N5→N1 (0-based). */
export function kanjiLearnIndex(character: string) {
  const lesson = BY_CHAR.get(character);
  if (!lesson) return Number.POSITIVE_INFINITY;
  const before = KANJI_LESSONS.slice(0, lesson.seq - 1).reduce((n, l) => n + l.chars.length, 0);
  return before + [...lesson.chars].indexOf(character);
}

export const KANJI_LESSON_TOTAL = KANJI_LESSONS.length;

