export function hanVietOf(character: string) {
  return HAN_VIET[character] ?? "";
}

export function hanVietLabel(character: string) {
  const hv = hanVietOf(character);
  return hv ? `${character} · ${hv}` : character;
}

/** Hán-Việt từng chữ trong từ ghép: 日本語 → Nhật Bản Ngữ. */
export function hanVietOfWord(word: string) {
  const parts = [...word].map((c) => HAN_VIET[c]).filter(Boolean);
  return parts.join(" ");
}
